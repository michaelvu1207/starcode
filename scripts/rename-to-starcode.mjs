#!/usr/bin/env node
/**
 * One-shot codemod: upstream's `t3` identifiers -> `starcode`.
 *
 * Deliberately a script and not a fleet of agents. A token rename has to be
 * *provably* complete, and the only way to answer "did we get all of them" is a
 * deterministic pass plus a `git grep` that comes back empty. Overlapping
 * hand-edits across 1,300 files cannot offer that.
 *
 * Two rules do the real work:
 *
 *  - Replacements run longest-token-first. `@t3tools` has to be consumed before
 *    anything looks at `t3`, or the tail of a longer token gets rewritten out
 *    from under the pattern that owned it.
 *  - Nothing is rewritten on a line matching the deny list. That is what keeps
 *    `pingdotgg/t3code` — the actual upstream remote — intact.
 *
 * There is no bare `t3` -> `starcode` rule and there must never be one: it
 * would corrupt upstream URLs, commit hashes, base64 payloads, and any word
 * that happens to contain the digraph.
 *
 * Usage: node scripts/rename-to-starcode.mjs [--dry]
 */
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";

const DRY = process.argv.includes("--dry");

/** Longest first. Order is correctness here, not taste. */
const REPLACEMENTS = [
  ["@t3tools/", "@starcode/"],
  ["t3code-relay", "starcode-relay"],
  ["T3CODE_", "STARCODE_"],
  ["T3 Code", "starcode"],
  ["T3Code", "Starcode"],
  ["t3-code", "starcode"],
];

/**
 * A line matching any of these is left exactly as it is.
 *
 * `pingdotgg` is the load-bearing one: it carries the upstream repo URL, and
 * rewriting it silently breaks `git fetch upstream`.
 */
const PROTECTED_LINE = [
  /pingdotgg/,
  /upstream\/t3code/,
  // The migration sources. `legacyUserDataDirNames` and the tests pinning it
  // exist to read the pre-rename names, so rewriting them deletes the only
  // thing that finds a user's existing data.
  /legacy/i,
  /T3 Code \((Alpha|Dev)\)/,
];

/** Paths never opened at all. */
const PROTECTED_PATH = [
  /^\.repos\//, // vendored dependencies
  /^pnpm-lock\.yaml$/, // regenerated by pnpm, never sed'd
  /(^|\/)CHANGELOG[^/]*$/i, // shipped history stays as it shipped
  /^scripts\/rename-to-starcode\.mjs$/, // this file documents the old tokens
  // Historical archives. These record decisions as they were made, including
  // absolute paths on other developers' machines; rewriting them makes a record
  // of the past wrong rather than rebranding anything.
  /^\.plans\//,
  // Attributed quotes. These are real posts by real people, with links; the
  // product name inside a quotation is part of what they said.
  /^apps\/marketing\/src\/lib\/tweets\.ts$/,
];

const isBinary = (buffer) => buffer.includes(0);

const files = NodeChildProcess.execFileSync("git", ["ls-files", "-z"], { maxBuffer: 1 << 28 })
  .toString("utf8")
  .split("\0")
  .filter(Boolean)
  .filter((path) => !PROTECTED_PATH.some((pattern) => pattern.test(path)));

let changedFiles = 0;
let changedLines = 0;
let protectedLines = 0;

for (const path of files) {
  let raw;
  try {
    if (!NodeFS.statSync(path).isFile()) continue;
    raw = NodeFS.readFileSync(path);
  } catch {
    continue; // vanished or unreadable; the grep gate will catch a miss
  }
  if (isBinary(raw)) continue;

  const before = raw.toString("utf8");
  if (!/t3|T3/.test(before)) continue;

  let fileTouched = false;
  const after = before
    .split("\n")
    .map((line) => {
      if (!/t3|T3/.test(line)) return line;
      if (PROTECTED_LINE.some((pattern) => pattern.test(line))) {
        protectedLines += 1;
        return line;
      }
      let next = line;
      for (const [from, to] of REPLACEMENTS) next = next.split(from).join(to);
      if (next !== line) {
        changedLines += 1;
        fileTouched = true;
      }
      return next;
    })
    .join("\n");

  if (fileTouched) {
    changedFiles += 1;
    if (!DRY) NodeFS.writeFileSync(path, after, "utf8");
  }
}

console.log(
  `${DRY ? "[dry] " : ""}${changedFiles} files, ${changedLines} lines rewritten, ` +
    `${protectedLines} protected lines skipped`,
);
